"""Small local object-store adapter with run-partitioned keys.

Production may replace this with S3/OSS/MinIO; callers only use ``put``,
``get``, ``delete`` and ``exists`` plus the opaque ``object://`` URI. The key
layout is generated by the service layer and always includes project and run,
so a run is a storage partition rather than a naming convention.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import tempfile
from pathlib import Path

URI_SCHEME = "object://"


class StorageError(RuntimeError):
    """Raised when an object cannot be read or written safely."""


def _normalise_key(key: str) -> str:
    key = key.strip().lstrip("/")
    if not key or key.endswith("/"):
        raise StorageError("object key must name a file")
    parts = Path(key).parts
    if any(part in ("", ".", "..") for part in parts):
        raise StorageError("object key contains an unsafe path segment")
    return "/".join(parts)


class ObjectStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).expanduser().resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def path_for(self, key: str) -> Path:
        normalised = _normalise_key(key)
        path = (self.root / normalised).resolve()
        if self.root not in path.parents:
            raise StorageError("object key escapes the storage root")
        return path

    def put(self, key: str, data: bytes) -> dict:
        path = self.path_for(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(prefix=".tmp-", dir=str(path.parent))
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp_name, path)
        except Exception:
            try:
                os.unlink(tmp_name)
            except FileNotFoundError:
                pass
            raise
        return {
            "key": _normalise_key(key),
            "uri": URI_SCHEME + _normalise_key(key),
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        }

    def get(self, key: str) -> bytes:
        path = self.path_for(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise StorageError(f"object not found: {key}") from exc

    def exists(self, key: str) -> bool:
        try:
            return self.path_for(key).is_file()
        except StorageError:
            return False

    def delete(self, key: str) -> bool:
        path = self.path_for(key)
        try:
            path.unlink()
            return True
        except FileNotFoundError:
            return False

    def list_objects(self, prefix: str = "") -> list[str]:
        base = self.path_for(prefix.rstrip("/") + "/x").parent if prefix else self.root
        if not base.is_dir():
            return []
        return sorted(
            str(path.relative_to(self.root))
            for path in base.rglob("*")
            if path.is_file() and not path.name.startswith(".tmp-")
        )

    def reset(self) -> None:
        """Test helper: remove all stored objects (never called by services)."""

        if self.root.exists():
            shutil.rmtree(self.root)
        self.root.mkdir(parents=True, exist_ok=True)
